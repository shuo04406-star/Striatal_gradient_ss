def ordered_stage_roi_names(data: dict[str, pd.DataFrame]) -> dict[str, list[str]]:
    order = data["roi_order"].copy()
    assigned = order.loc[order["reward_stage"].isin(STAGES)].sort_values("roi_index")
    result = {
        stage: assigned.loc[assigned["reward_stage"].eq(stage), "roi_name"].astype(str).tolist()
        for stage in STAGES
    }
    require({key: len(value) for key, value in result.items()} == STAGE_N, "Stage ROI counts failed")
    return result


def build_roi_arrays(
    data: dict[str, pd.DataFrame], ordered_subjects: list[str], roi_names: dict[str, list[str]]
) -> dict[str, np.ndarray]:
    arrays: dict[str, np.ndarray] = {}
    index = pd.MultiIndex.from_product([ordered_subjects, range(1, 11)], names=["Subject", "Bin"])
    for stage in STAGES:
        part = data["roi"].loc[data["roi"]["RewardStage"].eq(stage)]
        wide = part.pivot(index=["Subject", "Bin"], columns="ROI", values="FC").reindex(
            index=index, columns=roi_names[stage]
        )
        require(not wide.isna().any().any(), f"Missing ROI array values for {stage}")
        arrays[stage] = wide.to_numpy(float).reshape(64, 10, len(roi_names[stage]))
    return arrays


def y_from_arrays(arrays: dict[str, np.ndarray], stage: str | None = None, combo: tuple[int, ...] = ()) -> np.ndarray:
    matrices: dict[str, np.ndarray] = {}
    for current in STAGES:
        source = arrays[current]
        if current == stage:
            keep_sum = source.sum(axis=2) - source[:, :, list(combo)].sum(axis=2)
            matrices[current] = keep_sum / (source.shape[2] - len(combo))
        else:
            matrices[current] = source.mean(axis=2)
    return np.concatenate([matrices["Outcome"], matrices["Anticipation"]], axis=1)


def target_combos(
    data: dict[str, pd.DataFrame], roi_names: dict[str, list[str]], subfamilies: pd.DataFrame
) -> dict[str, tuple[int, ...]]:
    order = data["roi_order"].copy()
    result: dict[str, tuple[int, ...]] = {}
    for row in subfamilies.itertuples(index=False):
        names = order.loc[
            order["reward_stage"].eq(row.stage) & order["subfamily"].eq(row.subfamily), "roi_name"
        ].astype(str)
        mapping = {name: index for index, name in enumerate(roi_names[row.stage])}
        combo = tuple(sorted(mapping[name] for name in names))
        require(len(combo) == int(row.deleted_roi_count), f"Target combination mismatch: {row.subfamily}")
        result[row.subfamily] = combo
    return result


def profile_metrics(delta: np.ndarray) -> dict[str, float]:
    offset = float(np.mean(delta))
    centered = delta - offset
    shape = float(np.sqrt(np.mean(centered**2)))
    total = float(np.sqrt(np.mean(delta**2)))
    identity_error = abs(total**2 - offset**2 - shape**2)
    if total > 0:
        offset_share = float(offset**2 / total**2)
        shape_share = float(shape**2 / total**2)
    else:
        offset_share = np.nan
        shape_share = np.nan
    return {
        "offset_change": offset,
        "absolute_offset_change": abs(offset),
        "shape_rmse": shape,
        "total_rmse": total,
        "maximum_absolute_bin_change": float(np.max(np.abs(delta))),
        "offset_share_squared": offset_share,
        "shape_share_squared": shape_share,
        "decomposition_identity_error": identity_error,
    }


def full_d_profiles(arrays: dict[str, np.ndarray]) -> dict[str, np.ndarray]:
    result = {}
    for stage in STAGES:
        stage_mean = arrays[stage].mean(axis=2)
        result[stage] = stage_mean[32:].mean(axis=0) - stage_mean[:32].mean(axis=0)
    return result


def deleted_d_profile(arrays: dict[str, np.ndarray], stage: str, combo: tuple[int, ...]) -> np.ndarray:
    source = arrays[stage]
    deleted = (source.sum(axis=2) - source[:, :, list(combo)].sum(axis=2)) / (source.shape[2] - len(combo))
    return deleted[32:].mean(axis=0) - deleted[:32].mean(axis=0)


def fit_observed_targets(
    arrays: dict[str, np.ndarray],
    subfamilies: pd.DataFrame,
    targets: dict[str, tuple[int, ...]],
    x: np.ndarray,
    z: np.ndarray,
    groups: np.ndarray,
) -> tuple[pd.DataFrame, dict[str, np.ndarray]]:
    records = []
    starts: dict[str, np.ndarray] = {}
    full_y = y_from_arrays(arrays)
    full_result, full_opt, full_warn = s3a.fit_matrix_model(full_y.reshape(-1), x, groups, z)
    full_beta = float(s3a.effect_rows(full_result)[0]["estimate"])
    starts["Full"] = np.asarray(full_result.params)
    records.append(
        {"model": "Full", "subfamily": "Full", "stage": "Both", "beta": full_beta, "delta_beta": 0.0,
         "optimizer": full_opt, "converged": bool(full_result.converged), "warnings": full_warn}
    )
    for row in subfamilies.itertuples(index=False):
        y = y_from_arrays(arrays, row.stage, targets[row.subfamily])
        result, optimizer, warning_text = s3a.fit_matrix_model(
            y.reshape(-1), x, groups, z, start_params=np.asarray(full_result.params)
        )
        beta = float(s3a.effect_rows(result)[0]["estimate"])
        starts[row.subfamily] = np.asarray(result.params)
        records.append(
            {"model": f"Minus {row.subfamily}", "subfamily": row.subfamily, "stage": row.stage,
             "beta": beta, "delta_beta": beta - full_beta, "optimizer": optimizer,
             "converged": bool(result.converged), "warnings": warning_text}
        )
    return pd.DataFrame(records), starts


def make_decomposition(
    arrays: dict[str, np.ndarray], subfamilies: pd.DataFrame, targets: dict[str, tuple[int, ...]]
) -> pd.DataFrame:
    full = full_d_profiles(arrays)
    rows = []
    for target in subfamilies.itertuples(index=False):
        for stage in STAGES:
            deleted = (
                deleted_d_profile(arrays, stage, targets[target.subfamily])
                if stage == target.stage else full[stage].copy()
            )
            delta = deleted - full[stage]
            metrics = profile_metrics(delta)
            largest = np.argsort(np.abs(delta))[::-1][:3] + 1
            row = {
                "subfamily": target.subfamily,
                "target_stage": target.stage,
                "stage": stage,
                "deleted_roi_count": int(target.deleted_roi_count),
                "stage_is_affected": stage == target.stage,
                **metrics,
                "largest_absolute_change_bins": "; ".join(str(value) for value in largest),
                "all_bin_changes_same_direction": bool(np.all(delta >= 0) or np.all(delta <= 0)),
            }
            for index in range(10):
                row[f"full_D_bin{index + 1}"] = float(full[stage][index])
                row[f"deleted_D_bin{index + 1}"] = float(deleted[index])
                row[f"delta_D_bin{index + 1}"] = float(delta[index])
                row[f"centered_change_bin{index + 1}"] = float(delta[index] - metrics["offset_change"])
            rows.append(row)
    return pd.DataFrame(rows)


def generate_combinations(
    subfamilies: pd.DataFrame, targets: dict[str, tuple[int, ...]], roi_names: dict[str, list[str]]
) -> pd.DataFrame:
    rows = []
    unique = subfamilies[["stage", "deleted_roi_count"]].drop_duplicates().sort_values(
        ["stage", "deleted_roi_count"]
    )
    for stratum_index, item in enumerate(unique.itertuples(index=False)):
        stage = item.stage
        k = int(item.deleted_roi_count)
        n = STAGE_N[stage]
        total_space = math.comb(n, k)
        stage_targets = {
            targets[row.subfamily]
            for row in subfamilies.itertuples(index=False)
            if row.stage == stage and int(row.deleted_roi_count) == k
        }
        if total_space <= PROFILE_RANDOM_TARGET:
            combos = list(itertools.combinations(range(n), k))
            mode = "complete_enumeration"
        else:
            rng = np.random.default_rng(np.random.SeedSequence([COMBO_SEED, stratum_index, n, k]))
            seen: set[tuple[int, ...]] = set()
            combos = []
            while len(combos) < PROFILE_RANDOM_TARGET:
                combo = tuple(sorted(rng.choice(n, size=k, replace=False).tolist()))
                if combo in seen or combo in stage_targets:
                    continue
                seen.add(combo)
                combos.append(combo)
            mode = "unique_monte_carlo"
        mixed_count = min(len(combos), MIXEDLM_RANDOM_TARGET)
        for combo_index, combo in enumerate(combos):
            rows.append(
                {
                    "stratum_id": f"{stage}_k{k}",
                    "stage": stage,
                    "deleted_roi_count": k,
                    "combo_id": f"{stage}_k{k}_{combo_index + 1:05d}",
                    "combination_mode": mode,
                    "combination_space_size": total_space,
                    "roi_indices_within_stage": ";".join(str(value) for value in combo),
                    "roi_names": "; ".join(roi_names[stage][value] for value in combo),
                    "is_any_target_combination": combo in stage_targets,
                    "used_for_profile_benchmark": True,
                    "used_for_mixedlm_benchmark": combo_index < mixed_count,
                }
            )
    result = pd.DataFrame(rows)
    require(not result.duplicated(["stage", "deleted_roi_count", "roi_indices_within_stage"]).any(), "Duplicate combinations")
    return result


def combo_tuple(value: str) -> tuple[int, ...]:
    return tuple(int(item) for item in str(value).split(";") if str(item) != "")


def compute_random_profile_metrics(
    arrays: dict[str, np.ndarray], manifest: pd.DataFrame
) -> pd.DataFrame:
    full = full_d_profiles(arrays)
    records = []
    for (stage, k), part in manifest.groupby(["stage", "deleted_roi_count"], sort=False):
        source = arrays[stage]
        roi_d = source[32:].mean(axis=0).T - source[:32].mean(axis=0).T  # ROI x bin
        all_sum = roi_d.sum(axis=0)
        combos = np.asarray([combo_tuple(value) for value in part["roi_indices_within_stage"]], dtype=int)
        for start in range(0, len(part), 500):
            stop = min(start + 500, len(part))
            batch = combos[start:stop]
            deleted = (all_sum[None, :] - roi_d[batch].sum(axis=1)) / (source.shape[2] - int(k))
            delta = deleted - full[stage][None, :]
            offset = delta.mean(axis=1)
            centered = delta - offset[:, None]
            shape = np.sqrt(np.mean(centered**2, axis=1))
            total = np.sqrt(np.mean(delta**2, axis=1))
            maximum = np.max(np.abs(delta), axis=1)
            for local, combo_id in enumerate(part.iloc[start:stop]["combo_id"]):
                records.append(
                    {"combo_id": combo_id, "stage": stage, "deleted_roi_count": int(k),
                     "total_rmse": float(total[local]), "offset_change": float(offset[local]),
                     "absolute_offset_change": float(abs(offset[local])), "shape_rmse": float(shape[local]),
                     "maximum_absolute_bin_change": float(maximum[local])}
                )
    return pd.DataFrame(records)


def empirical_summary(values: np.ndarray, target: float, absolute_target: bool = False) -> dict[str, float]:
    values = np.asarray(values, dtype=float)
    target_value = abs(target) if absolute_target else target
    compare = np.abs(values) if absolute_target else values
    less = int(np.sum(compare < target_value))
    equal = int(np.sum(np.isclose(compare, target_value, atol=1e-15, rtol=1e-12)))
    percentile = 100.0 * (less + 0.5 * equal) / len(compare)
    upper = float(np.mean(compare >= target_value))
    return {
        "random_mean": float(np.mean(compare)), "random_median": float(np.median(compare)),
        "random_q2_5": float(np.quantile(compare, 0.025)), "random_q25": float(np.quantile(compare, 0.25)),
        "random_q75": float(np.quantile(compare, 0.75)), "random_q97_5": float(np.quantile(compare, 0.975)),
        "target_percentile": percentile, "empirical_upper_tail_fraction": upper,
        "monte_carlo_percentile_se_pp": 100.0 * math.sqrt((percentile / 100) * (1 - percentile / 100) / len(compare)),
    }


def build_profile_benchmark(
    subfamilies: pd.DataFrame,
    targets: dict[str, tuple[int, ...]],
    decomposition: pd.DataFrame,
    manifest: pd.DataFrame,
    random_metrics: pd.DataFrame,
) -> pd.DataFrame:
    rows = []
    joined = manifest.merge(random_metrics, on=["combo_id", "stage", "deleted_roi_count"], validate="one_to_one")
    affected = decomposition.loc[decomposition["stage_is_affected"]].set_index("subfamily")
    metrics = ["total_rmse", "absolute_offset_change", "shape_rmse", "maximum_absolute_bin_change"]
    for target in subfamilies.itertuples(index=False):
        combo_key = ";".join(str(value) for value in targets[target.subfamily])
        pool = joined.loc[
            joined["stage"].eq(target.stage)
            & joined["deleted_roi_count"].eq(int(target.deleted_roi_count))
            & joined["roi_indices_within_stage"].ne(combo_key)
        ]
        target_row = affected.loc[target.subfamily]
        base = {
            "subfamily": target.subfamily, "stage": target.stage,
            "deleted_roi_count": int(target.deleted_roi_count), "random_combination_mode": pool["combination_mode"].iloc[0],
            "combination_space_size": int(pool["combination_space_size"].iloc[0]), "valid_random_combinations": len(pool),
        }
        for metric in metrics:
            summary = empirical_summary(pool[metric].to_numpy(float), float(target_row[metric]))
            base[f"target_{metric}"] = float(target_row[metric])
            for name, value in summary.items():
                base[f"{metric}_{name}"] = value
            base[f"{metric}_upper_tail_flag_97_5"] = bool(summary["target_percentile"] >= 97.5)
        rows.append(base)
    return pd.DataFrame(rows)


def profile_subject_bootstrap(
    arrays: dict[str, np.ndarray], subfamilies: pd.DataFrame, targets: dict[str, tuple[int, ...]], reps: int
) -> pd.DataFrame:
    delta_by_subfamily: dict[str, np.ndarray] = {}
    for target in subfamilies.itertuples(index=False):
        source = arrays[target.stage]
        full = source.mean(axis=2)
        deleted = (source.sum(axis=2) - source[:, :, list(targets[target.subfamily])].sum(axis=2)) / (
            source.shape[2] - int(target.deleted_roi_count)
        )
        delta_by_subfamily[target.subfamily] = deleted - full
    values = {name: {"offset": [], "shape": [], "total": []} for name in delta_by_subfamily}
    for replicate in range(reps):
        rng = np.random.default_rng(np.random.SeedSequence([PROFILE_BOOT_SEED, replicate]))
        hc = rng.integers(0, 32, size=32)
        sz = rng.integers(32, 64, size=32)
        for name, subject_delta in delta_by_subfamily.items():
            delta = subject_delta[sz].mean(axis=0) - subject_delta[hc].mean(axis=0)
            metrics = profile_metrics(delta)
            values[name]["offset"].append(metrics["offset_change"])
            values[name]["shape"].append(metrics["shape_rmse"])
            values[name]["total"].append(metrics["total_rmse"])
    rows = []
    for name, metric_values in values.items():
        row = {"subfamily": name, "bootstrap_replicates": reps, "seed": PROFILE_BOOT_SEED}
        for metric, series in metric_values.items():
            array = np.asarray(series)
            row[f"{metric}_bootstrap_ci_low"] = float(np.quantile(array, 0.025))
            row[f"{metric}_bootstrap_ci_high"] = float(np.quantile(array, 0.975))
            row[f"{metric}_bootstrap_median"] = float(np.median(array))
        rows.append(row)
    return pd.DataFrame(rows)


def _mixed_initializer(stage_arrays, x, z, groups, start_params) -> None:
    global _WORK_STAGE_ARRAYS, _WORK_X, _WORK_Z, _WORK_GROUPS, _WORK_START, _WORK_FULL_Y
    _WORK_STAGE_ARRAYS = stage_arrays
    _WORK_X = x
    _WORK_Z = z
    _WORK_GROUPS = groups
    _WORK_START = start_params
    _WORK_FULL_Y = y_from_arrays(stage_arrays)


def _mixed_worker(task: dict[str, object]) -> dict[str, object]:
    assert _WORK_X is not None and _WORK_Z is not None and _WORK_GROUPS is not None and _WORK_START is not None
    stage = str(task["stage"])
    combo = tuple(int(value) for value in task["combo"])
    try:
        y = y_from_arrays(_WORK_STAGE_ARRAYS, stage, combo)
        result, optimizer, warning_text = s3a.fit_matrix_model(
            y.reshape(-1), _WORK_X, _WORK_GROUPS, _WORK_Z, start_params=_WORK_START
        )
        beta = float(s3a.effect_rows(result)[0]["estimate"])
        return {**task, "success": True, "beta": beta, "optimizer": optimizer, "warnings": warning_text, "error": ""}
    except Exception as exc:
        return {**task, "success": False, "beta": np.nan, "optimizer": "", "warnings": "", "error": repr(exc)}


def mixed_tasks(manifest: pd.DataFrame) -> list[dict[str, object]]:
    part = manifest.loc[manifest["used_for_mixedlm_benchmark"]].copy()
    return [
        {"combo_id": row.combo_id, "stage": row.stage, "deleted_roi_count": int(row.deleted_roi_count),
         "combo": list(combo_tuple(row.roi_indices_within_stage))}
        for row in part.itertuples(index=False)
    ]


def load_jsonl(path: Path) -> dict[str, dict[str, object]]:
    result = {}
    if not path.exists():
        return result
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            item = json.loads(line)
            result[str(item["combo_id"])] = item
        except Exception as exc:
            raise RuntimeError(f"Invalid checkpoint line {line_number}: {exc}") from exc
    return result


def run_mixed_tasks(
    tasks: list[dict[str, object]], arrays: dict[str, np.ndarray], x: np.ndarray, z: np.ndarray,
    groups: np.ndarray, start_params: np.ndarray, workers: int, limit: int | None = None
) -> tuple[pd.DataFrame, float]:
    checkpoint = LOGS / "count_matched_mixedlm_checkpoint.jsonl"
    completed = load_jsonl(checkpoint)
    selected = tasks if limit is None else tasks[:limit]
    missing = [task for task in selected if str(task["combo_id"]) not in completed]
    started = time.perf_counter()
    if missing:
        context = mp.get_context("spawn")
        with checkpoint.open("a", encoding="utf-8", buffering=1) as handle:
            with context.Pool(
                processes=workers, initializer=_mixed_initializer,
                initargs=(arrays, x, z, groups, start_params),
            ) as pool:
                for number, result in enumerate(pool.imap_unordered(_mixed_worker, missing, chunksize=1), start=1):
                    handle.write(json.dumps(result, ensure_ascii=False) + "\n")
                    handle.flush()
                    completed[str(result["combo_id"])] = result
                    if number % 25 == 0 or number == len(missing):
                        logging.info("Count-matched MixedLM progress: %d/%d newly fitted", number, len(missing))
    elapsed = time.perf_counter() - started
    frame = pd.DataFrame([completed[str(task["combo_id"])] for task in selected])
    return frame, elapsed


def _boot_initializer(full_y, deleted_y, x, z, groups, full_start, deleted_start, seed) -> None:
    global _WORK_FULL_Y, _BOOT_DELETED_Y, _WORK_X, _WORK_Z, _WORK_GROUPS, _WORK_START, _BOOT_SEED
    _WORK_FULL_Y = full_y
    _BOOT_DELETED_Y = deleted_y
    _WORK_X = x
    _WORK_Z = z
    _WORK_GROUPS = groups
    _WORK_START = (full_start, deleted_start)
    _BOOT_SEED = seed


def _boot_worker(replicate: int) -> dict[str, object]:
    assert _WORK_FULL_Y is not None and _BOOT_DELETED_Y is not None
    assert _WORK_X is not None and _WORK_Z is not None and _WORK_GROUPS is not None and _WORK_START is not None
    rng = np.random.default_rng(np.random.SeedSequence([_BOOT_SEED, replicate]))
    draw = np.concatenate([rng.integers(0, 32, size=32), rng.integers(32, 64, size=32)])
    output = {"replicate": replicate, "success": False, "full_beta": np.nan, "deleted_beta": np.nan,
              "delta_beta": np.nan, "full_optimizer": "", "deleted_optimizer": "", "error": ""}
    try:
        full, full_opt, _ = s3a.fit_matrix_model(
            _WORK_FULL_Y[draw].reshape(-1), _WORK_X, _WORK_GROUPS, _WORK_Z, start_params=_WORK_START[0]
        )
        deleted, deleted_opt, _ = s3a.fit_matrix_model(
            _BOOT_DELETED_Y[draw].reshape(-1), _WORK_X, _WORK_GROUPS, _WORK_Z, start_params=_WORK_START[1]
        )
        full_beta = float(s3a.effect_rows(full)[0]["estimate"])
        deleted_beta = float(s3a.effect_rows(deleted)[0]["estimate"])
        output.update({"success": True, "full_beta": full_beta, "deleted_beta": deleted_beta,
                       "delta_beta": deleted_beta - full_beta, "full_optimizer": full_opt,
                       "deleted_optimizer": deleted_opt})
    except Exception as exc:
        output["error"] = repr(exc)
    return output


def insula_bootstrap(
    arrays: dict[str, np.ndarray], target: tuple[int, ...], x: np.ndarray, z: np.ndarray,
    groups: np.ndarray, starts: dict[str, np.ndarray], reps: int, workers: int
) -> pd.DataFrame:
    checkpoint = LOGS / "insula_bootstrap_checkpoint.jsonl"
    completed: dict[int, dict[str, object]] = {}
    if checkpoint.exists():
        for line_number, line in enumerate(checkpoint.read_text(encoding="utf-8").splitlines(), start=1):
            if not line.strip():
                continue
            try:
                item = json.loads(line)
                completed[int(item["replicate"])] = item
            except Exception as exc:
                raise RuntimeError(f"Invalid Insula checkpoint line {line_number}: {exc}") from exc
    missing = [replicate for replicate in range(reps) if replicate not in completed]
    logging.info("Insula paired bootstrap: recovered=%d missing=%d", len(completed), len(missing))
    if missing:
        context = mp.get_context("spawn")
        full_y = y_from_arrays(arrays)
        deleted_y = y_from_arrays(arrays, "Anticipation", target)
        with checkpoint.open("a", encoding="utf-8", buffering=1) as handle:
            with context.Pool(
                processes=workers, initializer=_boot_initializer,
                initargs=(full_y, deleted_y, x, z, groups, starts["Full"], starts["Insula"], INSULA_BOOT_SEED),
            ) as pool:
                for number, result in enumerate(pool.imap_unordered(_boot_worker, missing, chunksize=1), start=1):
                    handle.write(json.dumps(result, ensure_ascii=False) + "\n")
                    handle.flush()
                    completed[int(result["replicate"])] = result
                    if number % 100 == 0 or number == len(missing):
                        logging.info("Insula bootstrap progress: %d/%d newly fitted", number, len(missing))
    frame = pd.DataFrame([completed[index] for index in range(reps)])
    require(frame["success"].sum() >= math.ceil(0.95 * reps), "Insula bootstrap has fewer than 95% valid replicates")
    return frame


