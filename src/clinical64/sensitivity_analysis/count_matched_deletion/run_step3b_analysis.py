def full_phase() -> None:
    context = rebuild_context()
    tasks = mixed_tasks(context["manifest"])
    mixed, elapsed = run_mixed_tasks(
        tasks, context["arrays"], context["x"], context["z"], context["groups"],
        context["starts"]["Full"], WORKERS, limit=None
    )
    require(len(mixed) == len(tasks), "MixedLM result/task count mismatch")
    write_tsv(mixed, TABLES / "mixedlm_random_deletion_results.tsv")
    effect = build_effect_benchmark(
        context["subfamilies"], context["targets"], context["observed"], context["manifest"], mixed
    )
    write_tsv(effect, TABLES / "roi_count_matched_effect_benchmark.tsv")

    decomposition = pd.read_csv(TABLES / "profile_offset_shape_decomposition.tsv", sep="\t")
    profile = pd.read_csv(TABLES / "roi_count_matched_profile_benchmark.tsv", sep="\t")
    percentiles = percentile_long(effect, profile)
    write_tsv(percentiles, TABLES / "subfamily_random_deletion_percentiles.tsv")

    insula = insula_bootstrap(
        context["arrays"], context["targets"]["Insula"], context["x"], context["z"], context["groups"],
        context["starts"], INSULA_BOOT_REPS, WORKERS
    )
    write_tsv(insula, TABLES / "insula_bootstrap_recheck.tsv")
    build_reports_and_summary(effect, profile, decomposition, insula, mixed)

    performance = pd.read_csv(LOGS / "mixedlm_performance_test.tsv", sep="\t")
    hashes = pd.read_csv(TABLES / "input_sha256.tsv", sep="\t")
    qc = json.loads((LOGS / "audit_state.json").read_text(encoding="utf-8"))
    write_qc_report(qc, hashes, context["subfamilies"], context["manifest"], performance, mixed, insula)

    checkpoint = LOGS / "count_matched_mixedlm_checkpoint.jsonl"
    if checkpoint.exists():
        checkpoint.unlink()
    insula_checkpoint = LOGS / "insula_bootstrap_checkpoint.jsonl"
    if insula_checkpoint.exists():
        insula_checkpoint.unlink()
    logging.info("STEP 3B full analysis complete; new MixedLM elapsed seconds=%.3f", elapsed)


