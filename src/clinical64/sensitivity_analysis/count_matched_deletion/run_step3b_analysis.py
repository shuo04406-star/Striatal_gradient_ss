def performance_phase() -> None:
    context = rebuild_context()
    tasks = mixed_tasks(context["manifest"])
    # Cover every stage/count stratum in the 100-fit timing test.  Taking the
    # first 100 manifest rows would over-represent the first sorted strata.
    strata: dict[tuple[str, int], list[dict[str, object]]] = {}
    for task in tasks:
        key = (str(task["stage"]), int(task["deleted_roi_count"]))
        strata.setdefault(key, []).append(task)
    performance_tasks: list[dict[str, object]] = []
    offsets = {key: 0 for key in strata}
    while len(performance_tasks) < min(100, len(tasks)):
        made_progress = False
        for key in sorted(strata):
            offset = offsets[key]
            if offset < len(strata[key]):
                performance_tasks.append(strata[key][offset])
                offsets[key] += 1
                made_progress = True
                if len(performance_tasks) >= min(100, len(tasks)):
                    break
        if not made_progress:
            break
    full_start = context["starts"]["Full"]
    results, elapsed = run_mixed_tasks(
        performance_tasks, context["arrays"], context["x"], context["z"], context["groups"], full_start, WORKERS
    )
    success = int(results["success"].sum())
    per_fit = elapsed / max(len(results), 1)
    projected = per_fit * len(tasks)
    performance = pd.DataFrame([{
        "test_fits": len(results), "successful_fits": success, "failed_fits": len(results) - success,
        "elapsed_seconds_new_work": elapsed, "seconds_per_fit_wall": per_fit,
        "total_planned_unique_fits": len(tasks), "projected_full_seconds": projected,
        "workers": WORKERS, "replacement_model_used": False,
    }])
    write_tsv(performance, LOGS / "mixedlm_performance_test.tsv")
    require(success == len(results), "Performance test contained MixedLM failures")
    require(projected < 4 * 3600, f"Projected count-matched MixedLM runtime exceeds four hours: {projected:.1f}s")
    logging.info("Performance test complete: %s", performance.iloc[0].to_dict())


